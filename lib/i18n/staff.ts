export const STAFF_DICTIONARIES: Record<Locale, StaffDictionary> = { pl, en, ru, uz };

export function getStaffDictionary(locale: Locale): StaffDictionary {
  return STAFF_DICTIONARIES[locale];
}

export function formatStaffMessage(
  message: string,
  values: Record<string, string | number>,
): string {
  return message.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}

export function reservationStatusLabel(dictionary: StaffDictionary, status: string): string {
  const labels: Record<string, string> = {
    pending: dictionary.statusPending,
    confirmed: dictionary.statusConfirmed,
    seated: dictionary.statusSeated,
    completed: dictionary.statusCompleted,
    cancelled: dictionary.statusCancelled,
    no_show: dictionary.statusNoShow,
  };
  return labels[status] ?? status;
}

export function floorStateLabel(dictionary: StaffDictionary, state: string): string {
  const labels: Record<string, string> = {
    available: dictionary.floorAvailable,
    occupied: dictionary.floorOccupied,
    reserved: dictionary.floorReserved,
    held: dictionary.floorHeld,
    blocked: dictionary.floorBlocked,
  };
  return labels[state] ?? state;
}
